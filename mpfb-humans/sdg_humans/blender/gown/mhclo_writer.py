"""Write the gown as an MPFB clothes asset using MPFB's own MakeClothes services."""

import logging
import uuid
from pathlib import Path

_LOG = logging.getLogger("sdg_humans.blender.gown")

_MHMAT = """# MakeHuman material generated by mpfb-humans
name {name}
diffuseColor 0.9 0.9 0.9
diffuseTexture textures/stripes_mask.png
shininess 0.1
"""


def write_asset(ns, basemesh, gown, out_dir: Path, name: str, cfg: dict) -> Path:
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    ns.GeneralObjectProperties.set_value("object_type", "Clothes", entity_reference=gown)
    check = ns.ClothesService.mesh_is_valid_as_clothes(gown, basemesh)
    if not check["all_checks_ok"]:
        raise RuntimeError(f"gown mesh failed MakeClothes checks: {check}")
    props = {"name": name, "uuid": str(uuid.uuid5(uuid.NAMESPACE_URL, f"synthetic-humans/{name}")),  # former project name: keeps asset uuids stable
             "author": cfg.get("author", ""), "license": cfg.get("license", ""),
             "description": f"{'Office skirt' if 'skirt' in name else 'Hospital gown'} ({name}) generated by mpfb-humans",
             "homepage": ""}
    mhclo = ns.ClothesService.create_mhclo_from_clothes_matching(basemesh, gown, properties_dict=props)
    mhclo.material = f"{name}.mhmat"
    path = out_dir / f"{name}.mhclo"
    mhclo.write_mhclo(str(path), also_export_mhmat=False, also_export_obj=True,
                      reference_scale=ns.ClothesService.get_reference_scale(basemesh))
    (out_dir / f"{name}.mhmat").write_text(_MHMAT.format(name=name), encoding="utf-8")
    _LOG.info(f"wrote {path} ({len(gown.data.vertices)} vertices)")
    return path
